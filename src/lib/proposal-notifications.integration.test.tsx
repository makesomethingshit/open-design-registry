import { afterAll, describe, expect, it, vi } from "vitest";
import { renderToStaticMarkup } from "react-dom/server";

const mocks = vi.hoisted(() => ({ getSession: vi.fn() }));
vi.mock("./auth", () => ({ auth: { api: { getSession: mocks.getSession } } }));
vi.mock("./session", () => ({ getSession: mocks.getSession }));
vi.mock("./storage", () => ({ publicAssetUrl: (value: string) => value, deleteObject: vi.fn() }));
vi.mock("./revision-bundle", () => ({ readRevisionBundle: vi.fn().mockResolvedValue(null) }));

if (process.env.TEST_DATABASE_URL) process.env.DATABASE_URL = process.env.TEST_DATABASE_URL;
const { prisma } = await import("./prisma");
const { createProjectProposal, reviewProposalChange, applyProposal, isVisible } = await import("./proposal-handlers");
const { GET } = await import("@/app/api/notifications/route");
const { PATCH } = await import("@/app/api/notifications/[id]/route");
const { default: NotificationsPage } = await import("@/app/notifications/page");
const databaseDescribe = process.env.TEST_DATABASE_URL ? describe : describe.skip;

function request(body: Record<string, unknown>, method = "POST") {
  return new Request("http://localhost/api/notifications", { method, headers: { "content-type": "application/json" }, body: JSON.stringify(body) });
}

async function fixture() {
  const suffix = crypto.randomUUID();
  const users = await Promise.all(["owner", "author", "watcher"].map((name) => prisma.user.create({ data: { id: `${name}-${suffix}`, name: `${name}-${suffix}`, email: `${name}-${suffix}@example.test` } })));
  const [owner, author, watcher] = users;
  const [target, source] = await Promise.all([owner, author].map((user) => prisma.project.create({ data: { slug: user.id, title: user.id, description: "", license: "MIT", coverUrl: "https://example.test/cover.png", ownerId: user.id } })));
  const [baseRevision, sourceRevision] = await Promise.all([target, source].map((project) => prisma.revision.create({ data: { projectId: project.id, number: 1, title: project.title, changeDescription: "Initial", sourceUrl: `https://example.test/${project.slug}.zip` } })));
  return { owner, author, watcher, target, source, baseRevision, sourceRevision };
}

async function withNotificationFailure(projectId: string, run: () => Promise<void>) {
  const name = `notification_failure_${crypto.randomUUID().replaceAll("-", "")}`;
  // Both identifiers are generated by this test; never interpolate request data.
  expect(projectId).toMatch(/^[a-z0-9]+$/);
  await prisma.$executeRawUnsafe(`CREATE FUNCTION "${name}"() RETURNS trigger AS $$ BEGIN RAISE EXCEPTION 'notification unavailable'; END; $$ LANGUAGE plpgsql`);
  await prisma.$executeRawUnsafe(`CREATE TRIGGER "${name}" BEFORE INSERT ON "Notification" FOR EACH ROW WHEN (NEW."projectId" = '${projectId}') EXECUTE FUNCTION "${name}"()`);
  try { await run(); } finally {
    await prisma.$executeRawUnsafe(`DROP TRIGGER "${name}" ON "Notification"`);
    await prisma.$executeRawUnsafe(`DROP FUNCTION "${name}"()`);
  }
}

databaseDescribe("Proposal lifecycle notifications in PostgreSQL", () => {
  afterAll(() => prisma.$disconnect());

  it("records one notification per mutation, serializes retries, and rolls back notification failures", async () => {
    const f = await fixture();
    mocks.getSession.mockResolvedValue({ user: f.author });
    const body = { baseRevisionId: f.baseRevision.id, sourceRevisionId: f.sourceRevision.id, title: "Improve navigation", body: "New navigation", requestId: crypto.randomUUID() };
    const create = () => createProjectProposal(request(body), { slug: f.target.slug });
    await withNotificationFailure(f.target.id, async () => { await expect(create()).rejects.toThrow("notification unavailable"); });
    expect(await prisma.proposal.count({ where: { projectId: f.target.id } })).toBe(0);
    const responses = await Promise.all([create(), create()]);
    expect(responses.map((response) => response.status).sort()).toEqual([200, 201]);
    const proposal = await responses[0].json();
    expect(await prisma.notification.findMany({ where: { proposalId: proposal.id } })).toMatchObject([{ recipientId: f.owner.id, actorId: f.author.id, type: "PROPOSAL_CREATED" }]);
    await prisma.projectWatch.create({ data: { userId: f.watcher.id, projectId: f.target.id } });
    mocks.getSession.mockResolvedValue({ user: f.owner });
    const scope = { id: proposal.id, changeId: proposal.changeSet.changes[0].id };
    const review = () => reviewProposalChange(request({ status: "APPROVED" }, "PATCH"), scope);
    await withNotificationFailure(f.target.id, async () => { expect((await review()).status).toBe(500); });
    expect(await prisma.change.findUnique({ where: { id: scope.changeId } })).toMatchObject({ reviewStatus: "PENDING" });
    expect(await prisma.changeReview.count({ where: { changeId: scope.changeId } })).toBe(0);
    expect((await review()).status).toBe(200);
    expect((await review()).status).toBe(200);
    const apply = () => applyProposal(request({ changeIds: [scope.changeId] }), { id: proposal.id });
    await withNotificationFailure(f.target.id, async () => { expect((await apply()).status).toBe(500); });
    expect(await prisma.revision.count({ where: { projectId: f.target.id } })).toBe(1);
    expect(await prisma.proposal.findUnique({ where: { id: proposal.id } })).toMatchObject({ status: "APPROVED" });
    const applied = await apply();
    expect(applied.status).toBe(201);
    const { revision } = await applied.json();
    expect((await apply()).status).toBe(200);
    const notifications = await prisma.notification.findMany({ where: { proposalId: proposal.id }, orderBy: { createdAt: "asc" } });
    expect(notifications.map(({ type }) => type)).toEqual(["PROPOSAL_CREATED", "PROPOSAL_APPROVED", "PROPOSAL_APPLIED"]);
    expect(notifications[2]).toMatchObject({ recipientId: f.author.id, actorId: f.owner.id, revisionId: revision.id });
    expect(await prisma.notification.findMany({ where: { recipientId: f.watcher.id } })).toMatchObject([{ type: "REVISION_PUBLISHED", revisionId: revision.id, proposalId: null }]);
  });

  it("filters real hidden metadata from the API, unread count, server page, and mark-as-read", async () => {
    const f = await fixture();
    const proposal = await prisma.proposal.create({ data: { projectId: f.target.id, proposalNumber: 1, authorId: f.author.id, baseRevisionId: f.baseRevision.id, sourceRevisionId: f.sourceRevision.id, title: "Secret proposal title", body: "Secret proposal body" } });
    const types = ["PROPOSAL_CREATED", "PROPOSAL_CHANGES_REQUESTED", "PROPOSAL_APPROVED", "PROPOSAL_APPLIED"] as const;
    await prisma.notification.createMany({ data: types.map((type) => ({ recipientId: f.watcher.id, actorId: f.author.id, projectId: f.target.id, proposalId: proposal.id, type, ...(type === "PROPOSAL_APPLIED" ? { revisionId: f.baseRevision.id } : {}) })) });
    mocks.getSession.mockResolvedValue({ user: f.watcher });
    const read = async () => (await GET(new Request("http://localhost/api/notifications"))).json();
    expect(await read()).toMatchObject({ unreadCount: 4, notifications: [{ proposal: { title: proposal.title } }, {}, {}, {}] });
    const notification = await prisma.notification.findFirstOrThrow({ where: { proposalId: proposal.id } });
    const hidden = async () => {
      const details = await prisma.proposal.findUniqueOrThrow({ where: { id: proposal.id }, include: { project: true, baseRevision: true, sourceRevision: { include: { project: true } } } });
      expect(isVisible(details, f.watcher.id)).toBe(false);
      expect(await read()).toEqual({ unreadCount: 0, notifications: [] });
      const html = renderToStaticMarkup(await NotificationsPage());
      for (const value of [proposal.title, f.author.name, f.target.title]) expect(html).not.toContain(value);
      expect((await PATCH(request({ read: true }, "PATCH"), { params: Promise.resolve({ id: notification.id }) })).status).toBe(404);
    };
    await prisma.project.update({ where: { id: f.source.id }, data: { isPublic: false } });
    await hidden();
    await prisma.project.update({ where: { id: f.source.id }, data: { ownerId: f.watcher.id } });
    expect((await read()).unreadCount).toBe(4);
    await prisma.project.update({ where: { id: f.target.id }, data: { isPublic: false } });
    await hidden();
    await prisma.project.update({ where: { id: f.target.id }, data: { ownerId: f.watcher.id } });
    expect((await read()).unreadCount).toBe(4);
    const draft = await prisma.revision.create({ data: { projectId: f.target.id, number: 2, title: "Draft", changeDescription: "Draft", sourceUrl: "https://example.test/draft.zip", isPublished: false } });
    await prisma.proposal.update({ where: { id: proposal.id }, data: { baseRevisionId: draft.id } });
    await hidden();
    await prisma.proposal.update({ where: { id: proposal.id }, data: { baseRevisionId: f.baseRevision.id, sourceRevisionId: draft.id } });
    await hidden();
    await prisma.proposal.update({ where: { id: proposal.id }, data: { sourceRevisionId: f.sourceRevision.id } });
    expect((await PATCH(request({ read: true }, "PATCH"), { params: Promise.resolve({ id: notification.id }) })).status).toBe(200);
    expect((await read()).unreadCount).toBe(3);
    await prisma.proposal.delete({ where: { id: proposal.id } });
    expect(await read()).toEqual({ unreadCount: 0, notifications: [] });
  });
});
