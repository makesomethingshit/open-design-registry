import { expect, test } from "@playwright/test";
import { PrismaClient } from "@prisma/client";
import { S3Client, PutObjectCommand, DeleteObjectCommand } from "@aws-sdk/client-s3";

test("moderation restores retained decisions with shared S3 covers and deleted reports", async ({ page, request }, testInfo) => {
  test.skip(!process.env.E2E_INTEGRATION, "requires isolated PostgreSQL and S3");
  test.setTimeout(120_000);
  const prisma = new PrismaClient();
  const s3 = new S3Client({ region: process.env.S3_REGION ?? "us-east-1", endpoint: process.env.S3_ENDPOINT, forcePathStyle: true, credentials: { accessKeyId: process.env.S3_ACCESS_KEY_ID!, secretAccessKey: process.env.S3_SECRET_ACCESS_KEY! } });
  const suffix = crypto.randomUUID();
  const email = `moderation-${suffix}@example.test`;
  const key = `covers/moderation-${suffix}/shared.png`;
  const unrelatedKey = `covers/moderation-${suffix}/unrelated.png`;
  const replacementKey = `covers/moderation-${suffix}/replacement.png`;
  const cover = `/api/assets?key=${encodeURIComponent(key)}`;
  const png = Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=", "base64");
  const signUp = await page.request.post("/api/auth/sign-up/email", { data: { name: "Synthetic moderator", email, password: "synthetic-moderation-password-123" } });
  expect(signUp.ok()).toBeTruthy();
  const admin = (await signUp.json()).user;
  await prisma.user.update({ where: { id: admin.id }, data: { role: "admin" } });
  const owner = await prisma.user.create({ data: { id: `owner-${suffix}`, name: "Owner A", email: `owner-${suffix}@example.test` } });
  const reporter = await prisma.user.create({ data: { id: `reporter-${suffix}`, name: "Synthetic reporter", email: `reporter-${suffix}@example.test` } });
  const a = await prisma.project.create({ data: { slug: `a-${suffix}`, title: "Shared cover A", description: "Synthetic", license: "MIT", coverUrl: cover, ownerId: owner.id } });
  const b = await prisma.project.create({ data: { slug: `b-${suffix}`, title: "Shared cover Fork B", description: "Synthetic", license: "MIT", coverUrl: cover, ownerId: admin.id, forkedFromProjectId: a.id } });
  const c = await prisma.project.create({ data: { slug: `c-${suffix}`, title: "Unrelated C", description: "Synthetic", license: "MIT", coverUrl: `/api/assets?key=${encodeURIComponent(unrelatedKey)}`, ownerId: admin.id } });
  const reports = await Promise.all(["Primary hide", "Duplicate hide", "Block A", "Block B", "Review only", "Dismissed"].map((name, index) => prisma.report.create({ data: { projectId: index === 3 ? b.id : a.id, reporterId: reporter.id, reason: `${name} ${suffix}`, details: "Synthetic preserved original reason" } })));
  const decide = (id: string, action: string) => page.request.patch(`/api/admin/reports/${id}`, { data: { status: "RESOLVED", action, resolutionNote: "Synthetic moderator decision" } });
  const asset = (url = cover) => request.get(url);
  try {
    for (const objectKey of [key, unrelatedKey, replacementKey]) await s3.send(new PutObjectCommand({ Bucket: process.env.S3_BUCKET!, Key: objectKey, Body: png, ContentType: "image/png" }));
    expect((await asset()).status()).toBe(200);
    await page.goto("/admin/reports");
    const panel = (reason: string) => page.locator(".card").filter({ has: page.getByText(reason, { exact: true }) });
    page.on("dialog", dialog => { void dialog.accept(); });
    await panel(reports[4].reason).getByRole("button", { name: "Mark as reviewed" }).click();
    await expect(panel(reports[4].reason)).toContainText("Report review complete");
    await expect(panel(reports[4].reason).getByRole("button")).toHaveCount(0);
    expect((await page.request.patch(`/api/admin/reports/${reports[5].id}`, { data: { status: "DISMISSED", action: "NONE" } })).status()).toBe(200);
    await page.reload();
    await expect(panel(reports[4].reason).getByRole("button")).toHaveCount(0);
    await expect(panel(reports[5].reason)).toContainText("DISMISSED");
    await expect(panel(reports[5].reason).getByRole("button")).toHaveCount(0);
    await panel(reports[0].reason).getByRole("button", { name: "Hide this project and resolve" }).click();
    await expect(panel(reports[0].reason)).toContainText("Only the reported project was hidden");
    expect((await request.get(`/api/projects/${a.slug}`)).status()).toBe(404);
    expect((await request.get(`/api/projects/${b.slug}`)).status()).toBe(200);
    const primary = panel(reports[0].reason);
    await expect(primary.getByRole("button", { name: "Hide this project and resolve" })).toHaveCount(0);
    await primary.getByRole("button", { name: "Block shared cover and resolve" }).click();
    await expect(primary).toContainText("The shared cover was blocked");
    await expect(primary.getByRole("button", { name: "Block shared cover and resolve" })).toHaveCount(0);
    expect((await asset()).status()).toBe(404);
    const primaryEvents = await prisma.moderationEvent.count({ where: { reportId: reports[0].id } });
    expect((await decide(reports[0].id, "HIDE_PROJECT")).status()).toBe(200);
    expect((await decide(reports[0].id, "BLOCK_COVER")).status()).toBe(200);
    expect(await prisma.moderationEvent.count({ where: { reportId: reports[0].id } })).toBe(primaryEvents);

    await panel(reports[1].reason).getByRole("button", { name: "Hide this project and resolve" }).click();
    await expect(panel(reports[1].reason).getByRole("alert")).toContainText("Another report already hides this project");
    expect((await prisma.report.findUniqueOrThrow({ where: { id: reports[1].id } })).status).toBe("OPEN");
    await panel(reports[0].reason).getByRole("button", { name: "Restore project visibility" }).click();
    await expect(panel(reports[0].reason)).toContainText("This project hide was lifted");
    expect((await request.get(`/api/projects/${a.slug}`)).status()).toBe(200);
    expect((await asset()).status()).toBe(404);
    await expect(primary.getByRole("button", { name: "Lift this report's asset blocks" })).toBeVisible();
    await primary.getByRole("button", { name: "Lift this report's asset blocks" }).click();
    await expect(primary).toContainText("This report's block was lifted");
    expect((await asset()).status()).toBe(200);
    await expect(primary.getByRole("button")).toHaveCount(0);
    await page.reload();
    await expect(panel(reports[0].reason).getByRole("button")).toHaveCount(0);

    expect((await decide(reports[1].id, "HIDE_PROJECT")).status()).toBe(200);
    expect((await decide(reports[1].id, "RESTORE_PROJECT")).status()).toBe(200);
    expect((await decide(reports[2].id, "BLOCK_COVER")).status()).toBe(200);
    await page.reload();
    const reverse = panel(reports[3].reason);
    await reverse.getByRole("button", { name: "Block shared cover and resolve" }).click();
    await expect(reverse).toContainText("The shared cover was blocked");
    await expect(reverse.getByRole("button", { name: "Block shared cover and resolve" })).toHaveCount(0);
    expect((await asset()).status()).toBe(404);
    expect((await page.request.get(cover)).status()).toBe(404);
    const legacy = `${process.env.S3_ENDPOINT}/${process.env.S3_BUCKET}/${key.replaceAll("/", "%2F")}`;
    expect((await asset(`/api/assets?url=${encodeURIComponent(legacy)}`)).status()).toBe(404);
    expect((await request.get(`/api/projects/${b.slug}`)).status()).toBe(200);
    expect((await request.get(`/api/projects/${c.slug}`)).status()).toBe(200);
    expect((await asset(`/api/assets?key=${encodeURIComponent(unrelatedKey)}`)).status()).toBe(200);
    await reverse.getByRole("button", { name: "Hide this project and resolve" }).click();
    await expect(reverse).toContainText("Only the reported project was hidden");
    await expect(reverse.getByRole("button", { name: "Hide this project and resolve" })).toHaveCount(0);
    await reverse.getByRole("button", { name: "Lift this report's asset blocks" }).click();
    await expect(reverse).toContainText("This report's block was lifted");
    expect((await request.get(`/api/projects/${b.slug}`)).status()).toBe(404);
    await expect(reverse.getByRole("button", { name: "Restore project visibility" })).toBeVisible();
    await reverse.getByRole("button", { name: "Block shared cover and resolve" }).click();
    await expect(reverse).toContainText("The shared cover was blocked");
    expect((await page.request.patch(`/api/projects/${b.slug}`, { data: { isPublic: true, rightsConfirmed: true } })).status()).toBe(409);
    expect((await page.request.patch(`/api/projects/${b.slug}`, { data: { isPublic: false } })).status()).toBe(200);
    expect((await decide(reports[3].id, "RESTORE_PROJECT")).status()).toBe(200);
    expect((await request.get(`/api/projects/${b.slug}`)).status()).toBe(404);
    expect((await page.request.patch(`/api/projects/${b.slug}`, { data: { isPublic: true, rightsConfirmed: true } })).status()).toBe(200);
    await prisma.project.update({ where: { id: a.id }, data: { coverUrl: `/api/assets?key=${encodeURIComponent(replacementKey)}` } });
    expect((await decide(reports[2].id, "BLOCK_COVER")).status()).toBe(200);
    expect((await asset(`/api/assets?key=${encodeURIComponent(replacementKey)}`)).status()).toBe(404);
    await prisma.project.update({ where: { id: a.id }, data: { coverUrl: c.coverUrl } });
    await prisma.user.delete({ where: { id: reporter.id } });
    expect(await prisma.report.count({ where: { id: { in: reports.map(r => r.id) } } })).toBe(0);
    expect((await asset()).status()).toBe(404);
    await page.reload();
    const retained = page.getByRole("region", { name: "Retained decisions with deleted reports" });
    await expect(retained).toContainText("Synthetic preserved original reason");
    await expect(retained).toContainText("Synthetic moderator decision");
    await page.setViewportSize({ width: 390, height: 844 });
    const blockA = panel(reports[2].reason);
    await blockA.scrollIntoViewIfNeeded();
    await page.screenshot({ path: testInfo.outputPath("moderation-retained.png"), fullPage: true });
    await blockA.getByRole("button", { name: "Lift this report's asset blocks" }).click();
    await expect(blockA).toContainText("This report's block was lifted");
    expect((await asset()).status()).toBe(404);
    await panel(reports[3].reason).getByRole("button", { name: "Lift this report's asset blocks" }).click();
    await expect(panel(reports[3].reason)).toContainText("This report's block was lifted");
    const restored = await asset();
    expect(restored.status()).toBe(200);
    expect(await restored.body()).toEqual(png);
    expect((await asset(`/api/assets?url=${encodeURIComponent(legacy)}`)).status()).toBe(200);
    expect(await prisma.moderationEvent.count({ where: { reportId: reports[2].id, reportReason: reports[2].reason, reportDetails: "Synthetic preserved original reason" } })).toBe(4);
    expect((await request.patch(`/api/admin/reports/${reports[2].id}`, { data: { action: "UNBLOCK_COVER" } })).status()).toBe(403);
  } finally {
    await prisma.moderationEvent.deleteMany({ where: { reportId: { in: reports.map(r => r.id) } } });
    await prisma.moderationProjectHold.deleteMany({ where: { projectId: { in: [a.id, b.id, c.id] } } });
    await prisma.moderationAssetBlock.deleteMany({ where: { reportId: { in: reports.map(r => r.id) } } });
    await prisma.project.deleteMany({ where: { id: { in: [a.id, b.id, c.id] } } });
    await prisma.user.deleteMany({ where: { id: { in: [admin.id, owner.id, reporter.id] } } });
    for (const objectKey of [key, unrelatedKey, replacementKey]) await s3.send(new DeleteObjectCommand({ Bucket: process.env.S3_BUCKET!, Key: objectKey }));
    await prisma.$disconnect();
    s3.destroy();
  }
});
